"""
SLO/SLI evaluator.

Reads config/slo.yaml, queries the current Prometheus scrape (or /metrics endpoint
of the local gateway) and reports:
  * current SLI value
  * budget remaining
  * burn rate at fast / slow windows

Also emits Prometheus recording rules (`generate_prometheus_rules()`) that a
Prometheus instance can `include` for real alerting.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Dict, List

import yaml

log = logging.getLogger("loc200.slo")

_SLO_FILE = Path("config/slo.yaml")


def load() -> Dict[str, Any]:
    if not _SLO_FILE.exists():
        return {}
    try:
        return yaml.safe_load(_SLO_FILE.read_text(encoding="utf-8")) or {}
    except Exception as exc:
        log.warning("cannot read %s: %s", _SLO_FILE, exc)
        return {}


def generate_prometheus_rules() -> str:
    """
    Produce a rules.yml snippet with recording + alerting rules for every SLO.
    Save to /etc/prometheus/rules/jerumednexus-slos.yml.
    """
    cfg = load()
    lines: List[str] = []
    lines.append("# Auto-generated by src/common/slo.py -- do not edit by hand.")
    lines.append("groups:")
    lines.append("  - name: jerumednexus.slos")
    lines.append("    rules:")

    for slo in cfg.get("slos", []):
        name = slo["name"]
        expr = slo["sli_expr"]
        target = slo.get("target")
        target_lt = slo.get("target_lt")
        severity = slo.get("severity", "medium")

        # Recording rule for the SLI itself
        lines += [
            f"      - record: jerumednexus_sli_{name}",
            f"        expr: {expr}",
            "",
        ]

        # Compliance rule (SLI relative to target)
        if target is not None:
            lines += [
                f"      - record: jerumednexus_slo_compliance_{name}",
                f"        expr: (jerumednexus_sli_{name} >= bool {target})",
                "",
                f"      - alert: SLOViolation_{name}",
                f"        expr: jerumednexus_sli_{name} < {target}",
                "        for: 15m",
                f"        labels: {{ severity: {severity}, slo: '{name}' }}",
                "        annotations:",
                f"          summary: 'SLO {name} below target {target}'",
                "",
            ]
        if target_lt is not None:
            lines += [
                f"      - alert: SLOViolation_{name}",
                f"        expr: jerumednexus_sli_{name} > {target_lt}",
                "        for: 10m",
                f"        labels: {{ severity: {severity}, slo: '{name}' }}",
                "        annotations:",
                f"          summary: 'SLO {name} above ceiling {target_lt}'",
                "",
            ]

    # Burn rate alerts
    burns = cfg.get("error_budgets", {}).get("burn_alerts", [])
    for burn in burns:
        for w in burn.get("windows", []):
            lines += [
                f"      - alert: BudgetBurn_{burn['name']}_{w}",
                f"        expr: (1 - avg_over_time(jerumednexus_sli_dispatch_success_rate[{w}])) > "
                f"({burn['factor']} * (1 - 0.999))",
                "        for: 5m",
                f"        labels: {{ severity: {burn.get('severity','ticket')} }}",
                "        annotations:",
                f"          summary: 'Fast error-budget burn ({burn['name']}) over {w}'",
                "",
            ]
    return "\n".join(lines)


def cli_dump() -> None:
    """Print the generated rules to stdout -- useful in CI."""
    print(generate_prometheus_rules())


if __name__ == "__main__":
    cli_dump()
